// Inlines the built widget (dist/widget) into a TS module so the MCP server
// can serve it without reading files at runtime (works the same on Vercel).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const js = "dist/widget/widget.js";
const css = "dist/widget/widget.css";
if (!existsSync(js)) {
  console.error("dist/widget/widget.js missing — run `npm run build:widget` first");
  process.exit(1);
}
mkdirSync("server/generated", { recursive: true });
const out = `// Generated by scripts/embed-widget.mjs — do not edit.
export const WIDGET_JS = ${JSON.stringify(readFileSync(js, "utf8"))};
export const WIDGET_CSS = ${JSON.stringify(existsSync(css) ? readFileSync(css, "utf8") : "")};
`;
writeFileSync("server/generated/widget.ts", out);
console.log(`embedded widget: ${(out.length / 1024).toFixed(0)} KB`);
